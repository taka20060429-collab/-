def set_japanese_font(run, font_name_jp="MS 明朝", font_name_en="Century", size=10.5):
    """日本語フォントと英数字フォントを設定"""
    run.font.name = font_name_en
    run.font.size = Pt(size)
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = rPr.makeelement(qn('w:rFonts'), {})
        rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), font_name_jp)
    rFonts.set(qn('w:ascii'), font_name_en)
    rFonts.set(qn('w:hAnsi'), font_name_en)


def add_paragraph(doc, text, size=10.5, bold=False, alignment=None,
                  first_line_indent=True, line_spacing=1.5):
    """段落を追加"""
    p = doc.add_paragraph()
    if alignment is not None:
        p.alignment = alignment
    pf = p.paragraph_format
    if first_line_indent:
        pf.first_line_indent = Pt(size)
    pf.line_spacing = line_spacing
    run = p.add_run(text)
    run.bold = bold
    set_japanese_font(run, size=size)
    return p


def add_heading(doc, text, level=1, size=12):
    """章立て見出しを追加"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf = p.paragraph_format
    pf.space_before = Pt(12)
    pf.space_after = Pt(6)
    run = p.add_run(text)
    run.bold = True
    set_japanese_font(run, size=size + (2 - level))
    return p


