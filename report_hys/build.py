def seg_table(title, segs):
    tn = nxt("tab")
    n = max(len(s_) for s_ in segs)
    rows = []
    for j in range(n):
        row = []
        for s_ in segs:
            if j < len(s_):
                row += [f"{s_[j][0]:.1f}", f"{s_[j][1]:.3f}" if s_[j][1] is not None else "【要記入】"]
            else:
                row += ["", ""]
        rows.append(row)
    hdr = []
    for k in range(5):
        hdr += [f"{SEG_SHORT[k]}\nI [A]", "B [T]"]
    table(title, tn, hdr, rows, [16, 16] * 5, size=8)
    return tn


