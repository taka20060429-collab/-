def segments(rows, n_up):
    """測定順のデータを (ⅰ)〜(ⅴ) の 5 区間に分ける。n_up は (ⅰ) の点数。"""
    k = (len(rows) - n_up) // 4
    s = [rows[:n_up]]
    for i in range(4):
        prev = s[-1][-1]
        s.append([prev] + rows[n_up + i * k: n_up + (i + 1) * k])
    return s


