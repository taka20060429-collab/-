def cross(seg):
    """区間の中で B が符号を変える電流（保磁力に対応）を直線補間で求める。"""
    for (i1, b1), (i2, b2) in zip(seg, seg[1:]):
        if b1 == 0:
            return i1
        if b1 * b2 < 0:
            return i1 + (i2 - i1) * (-b1) / (b2 - b1)
    return None


