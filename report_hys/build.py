def loop_chart(ws, segs, xname, xconv=None, h=10):
    """区間ごとに列を分けて書き込み，形と色を変えた折れ線つき散布図を作る。"""
    ch = low_labels(C.base_chart(xname, "磁束密度 B [T]", h=h))
    col = 1
    for k, (seg, name) in enumerate(zip(segs, SEG_SHORT)):
        ws.cell(row=1, column=col, value=name)
        ws.cell(row=2, column=col, value=xname)
        ws.cell(row=2, column=col + 1, value="B [T]")
        for j, (i, b) in enumerate(seg):
            ws.cell(row=3 + j, column=col, value=float(xconv(i) if xconv else i))
            ws.cell(row=3 + j, column=col + 1, value=float(b))
        s = Series(Reference(ws, min_col=col + 1, min_row=3, max_row=2 + len(seg)),
                   Reference(ws, min_col=col, min_row=3, max_row=2 + len(seg)), title=name)
        s.marker = C.marker(SYMS[k], 6, COLORS[k])
        C.line(s, COLORS[k], width=12700)
        ch.series.append(s)
        col += 3
    return ch


