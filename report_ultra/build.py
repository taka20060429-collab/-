def write_block(ws, col, rows, start, move, label, formula):
    """col 列から：番号, CH1, CH2, 角度。角度は式(2)。"""
    L = [chr(ord("A") + col + i) for i in range(4)]
    P = chr(ord("A") + col + 5)
    ws[f"{L[0]}1"] = label
    for j, h in enumerate(["番号（カウンタ）", "CH1 [V]", "CH2 [V]", "角度 [deg]"]):
        ws[f"{L[j]}2"] = h
    ws[f"{P}2"], ws[f"{chr(ord(P) + 1)}2"] = "移動開始角度 [deg]", start
    ws[f"{P}3"], ws[f"{chr(ord(P) + 1)}3"] = "移動角度 [deg]", move
    ws[f"{P}4"], ws[f"{chr(ord(P) + 1)}4"] = "総カウンタ数", len(rows)
    q = chr(ord(P) + 1)
    for i, r in enumerate(rows):
        k = i + 3
        ws[f"{L[0]}{k}"], ws[f"{L[1]}{k}"], ws[f"{L[2]}{k}"] = r
        ws[f"{L[3]}{k}"] = (f"=${q}$2+{L[0]}{k}*${q}$3/${q}$4" if formula
                            else start + r[0] * move / len(rows))
    return col + 3, col + 2, 3, 2 + len(rows)


def chart_for(ws, blocks, xr, step, names):
    ch = C.base_chart("角度 [deg]", "受音体出力電圧（CH2） [V]", h=9)
    for (xc, yc, r0, r1), color, name in zip(blocks, (C.BLUE, C.ORANGE), names):
        s = Series(Reference(ws, min_col=yc + 1, min_row=r0, max_row=r1),
                   Reference(ws, min_col=xc + 1, min_row=r0, max_row=r1), title=name)
        s.marker = Marker(symbol="none")
        C.line(s, color, width=15875)
        s.smooth = False
        ch.series.append(s)
    ch.x_axis.scaling.min, ch.x_axis.scaling.max, ch.x_axis.majorUnit = -xr, xr, step
    ch.y_axis.scaling.min = 0
    if len(names) == 1:
        ch.legend = None
    return ch


def make(ws, specs, labels, xr, step, formula):
    blocks = []
    for i, (spec, lab) in enumerate(zip(specs, labels)):
        rows = load(spec[0])
        blocks.append(write_block(ws, i * 9, [(r[0], r[1], r[2]) for r in rows], spec[1], spec[2], lab, formula))
    return chart_for(ws, blocks, xr, step, labels)


