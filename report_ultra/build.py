heading("6.5　音速と室温の関係式 v＝331＋0.6t の導出", 2)
body("音波が空気中を伝わるとき，圧縮と膨張は速く起こるので熱の出入りがない（断熱変化）とみなせる．"
     "このとき，理想気体中の音速は，比熱比を γ，気体定数を R，モル質量を M，絶対温度を T として")
e_vs = eq(r"v=\sqrt{\dfrac{\gamma RT}{M}}")
body("と表される．セルシウス温度 t［℃］を用いると T＝273.15＋t なので，0 ℃のときの音速を v_{0} とすれば")
e_v0 = eq(r"v=\sqrt{\dfrac{\gamma R(273.15+t)}{M}}=v_0\sqrt{1+\dfrac{t}{273.15}},\qquad v_0=\sqrt{\dfrac{\gamma R\times273.15}{M}}")
gam, R, M = 1.40, 8.314, 28.96e-3
v0 = math.sqrt(gam * R * 273.15 / M)
body(f"となる．空気の値 γ＝{gam:.2f}，R＝{R} J/(mol·K)，M＝{M * 1e3:.2f}×10⁻³ kg/mol を代入すると")
eq(rf"v_0=\sqrt{{\dfrac{{{gam:.2f}\times{R}\times273.15}}{{{M * 1e3:.2f}\times10^{{-3}}}}}}\simeq{v0:.0f}\ \mathrm{{m/s}}",
   numbered=False)
body("である．室温程度では t/273.15 は1よりずっと小さいので，|x|≪1 のときの近似 √(1＋x)≒1＋x/2 を使うと")
eq(rf"v\simeq v_0\left(1+\dfrac{{t}}{{2\times273.15}}\right)=v_0+\dfrac{{v_0}}{{546.3}}\,t"
   rf"\simeq{v0:.0f}+{v0 / 546.3:.2f}\,t", numbered=False)
body(f"となり，v＝331＋0.6t［m/s］が得られる．例えば本実験の室温{TEMP} ℃では，近似式は{v_th:.1f} m/s，"
     f"近似しない式(" + str(e_v0) + f")は{v0 * math.sqrt(1 + TEMP / 273.15):.1f} m/s であり，"
     f"差は{abs(v_th - v0 * math.sqrt(1 + TEMP / 273.15)):.1f} m/s しかない．室温付近ではこの近似式で十分である．")

